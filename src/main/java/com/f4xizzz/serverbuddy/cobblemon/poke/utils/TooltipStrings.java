package com.f4xizzz.serverbuddy.cobblemon.poke.utils;

public class TooltipStrings {
   public final String wordYes;
   public final String wordNo;
   public final String wordNone;
   public final String genderMale;
   public final String genderFemale;
   public final String genderNone;
   public final String haSuffix;

   public TooltipStrings(String wordYes, String wordNo, String wordNone, String genderMale, String genderFemale, String genderNone, String haSuffix) {
      this.wordYes = wordYes;
      this.wordNo = wordNo;
      this.wordNone = wordNone;
      this.genderMale = genderMale;
      this.genderFemale = genderFemale;
      this.genderNone = genderNone;
      this.haSuffix = haSuffix;
   }
}
