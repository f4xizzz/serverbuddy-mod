// Itens de ficha editados, cooldown dos gritos, permissões e /pokeodds setRate.
const fs = require('fs');
const t = require('./lib.js');

const TOKENS_CFG = 'D:/mods/ServerBuddy/run/config/ServerBuddy/PokeTokens/config.json';
const COBBLEMON_CFG = 'D:/mods/ServerBuddy/run/config/cobblemon/main.json';
const lastLines = (bot, n = 3) => bot.chatLog.slice(-n).join(' | ');

(async () => {
  const name = 'MxBot' + (Date.now() % 100000);
  console.log('== jogador de teste: ' + name);
  const bot = await t.join(name);
  t.rcon(`op ${name}`, `clear ${name}`, `clearparty ${name}`, `clearpc ${name}`);
  await t.sleep(500);

  console.log('== A) item da ficha editado na config');
  const original = fs.readFileSync(TOKENS_CFG, 'utf8');
  const cfg = t.parseJson(original);
  Object.assign(cfg.tokens.gender.item, { stackable: false, custom_model_data: 4242, hide_tooltip: true, hide_additional_tooltip: false, name: '<red>Editada <bold>%player%</bold>', lore: ['<aqua>linha 1', '<green>linha 2'] });
  cfg.tokens.shiny.item.stackable = true;
  fs.writeFileSync(TOKENS_CFG, JSON.stringify(cfg, null, 2));
  t.rcon('sb reload');
  await t.sleep(1500);
  t.rcon(`poketoken give ${name} gender 3`, `poketoken give ${name} shiny 5`);
  await t.sleep(1200);
  const items = bot.inventory.items();
  console.log('  inventário: ' + items.map((i) => `${i.slot}:${i.name}x${i.count}`).join(' '));
  const amethysts = items.filter((i) => i.name === 'amethyst_shard');
  t.check('stackable=false: 3 fichas em 3 pilhas separadas de 1', amethysts.length === 3 && amethysts.every((i) => i.count === 1), amethysts.map((i) => i.count).join(','));
  const stars = items.filter((i) => i.name === 'nether_star');
  t.check('stackable=true: 5 fichas numa pilha só', stars.length === 1 && stars[0].count === 5, stars.map((i) => i.count).join(','));
  const comps = (amethysts[0].components || []).map((c) => c.type);
  console.log('  componentes da ficha editada: ' + comps.join(','));
  t.check('tem custom_model_data, hide_tooltip e max_stack_size', ['custom_model_data', 'hide_tooltip', 'max_stack_size'].every((c) => comps.includes(c)));
  t.check('sem hide_additional_tooltip (false na config)', !comps.includes('hide_additional_tooltip'));
  const inv = t.rcon(`data get entity ${name} Inventory`);
  t.check('custom_model_data = 4242 no item', inv.includes('minecraft:custom_model_data": 4242') || inv.includes('custom_model_data": 4242') || inv.includes('4242'), (inv.match(/custom_model_data[^,}]*/) || [''])[0]);
  console.log('  ' + t.itemText(amethysts[0]));
  fs.writeFileSync(TOKENS_CFG, original);
  t.rcon('sb reload', `clear ${name}`);
  await t.sleep(1000);

  console.log('== B) cooldown dos gritos (op nível 2 não ignora o cooldown)');
  bot.chat('/givepokemon pikachu level=15');
  await t.sleep(1500);
  bot.chatLog.length = 0;
  bot.chat('/pokeshout 1');
  await t.sleep(1000);
  t.check('/pokeshout 1 funcionou', bot.chatLog.some((m) => m.includes('mostra')), lastLines(bot));
  bot.chatLog.length = 0;
  bot.chat('/pokeshout 1');
  await t.sleep(1000);
  t.check('/pokeshout de novo: espera o cooldown', bot.chatLog.some((m) => m.includes('Aguarde')), lastLines(bot));
  bot.chatLog.length = 0;
  bot.chat('/pokeshoutall');
  await t.sleep(1000);
  t.check('/pokeshoutall divide o mesmo cooldown', bot.chatLog.some((m) => m.includes('Aguarde')), lastLines(bot));
  t.rcon(`give ${name} minecraft:stick 1`);
  await t.sleep(800);
  const stick = bot.inventory.items().find((i) => i.name === 'stick');
  if (stick) await bot.equip(stick, 'hand');
  await t.sleep(500);
  bot.chatLog.length = 0;
  bot.chat('/itemshout');
  await t.sleep(900);
  t.check('/itemshout mostrou o item', bot.chatLog.some((m) => m.includes('mostra')), lastLines(bot));
  bot.chatLog.length = 0;
  bot.chat('/itemshout');
  await t.sleep(900);
  t.check('/itemshout de novo: cooldown', bot.chatLog.some((m) => m.includes('Aguarde')), lastLines(bot));

  console.log('== C) permissões (nível 2 x nível 0)');
  bot.chatLog.length = 0;
  bot.chat(`/sb storage add ${name} command say oi`);
  await t.sleep(900);
  t.check('o nível 2 NÃO consegue guardar um comando (precisa de nível 4)', bot.chatLog.some((m) => /Unknown|incomplete|Incorrect/i.test(m)), lastLines(bot));
  bot.chatLog.length = 0;
  bot.chat(`/sb storage add ${name} item minecraft:stone 1`);
  await t.sleep(900);
  t.check('o nível 2 consegue guardar um item', bot.chatLog.some((m) => m.includes('Reward sent')), lastLines(bot));
  t.rcon(`deop ${name}`);
  await t.sleep(800);
  bot.chatLog.length = 0;
  bot.chat('/pokesee');
  await t.sleep(900);
  t.check('sem op: /pokesee não existe para o jogador', bot.chatLog.some((m) => /Unknown|incomplete/i.test(m)), lastLines(bot));
  bot.chatLog.length = 0;
  bot.chat('/pokeshout 1');
  await t.sleep(900);
  t.check('sem op: /pokeshout não existe para o jogador', bot.chatLog.some((m) => /Unknown|incomplete/i.test(m)), lastLines(bot));
  bot.chatLog.length = 0;
  bot.chat('/itemshout');
  await t.sleep(900);
  t.check('sem op: /itemshout não existe para o jogador', bot.chatLog.some((m) => /Unknown|incomplete/i.test(m)), lastLines(bot));
  bot.chatLog.length = 0;
  bot.chat('/poketoken give ' + name + ' shiny 1');
  await t.sleep(900);
  t.check('sem op: /poketoken give não existe para o jogador', bot.chatLog.some((m) => /Unknown|incomplete/i.test(m)), lastLines(bot));
  let w = await t.openByCommand(bot, '/storage');
  t.check('sem op: /storage abre normalmente (nível 0)', !!w && t.titleOf(w).includes('Storage'), t.titleOf(w));
  console.log('  slots: ' + t.slots(w).slice(0, 3).join(' | '));
  bot.closeWindow(bot.currentWindow);
  t.rcon(`sb storage clear ${name}`);

  console.log('== D) /pokeodds');
  const before = JSON.parse(fs.readFileSync(COBBLEMON_CFG, 'utf8')).shinyRate;
  console.log('  shinyRate no arquivo antes: ' + before);
  console.log('  ' + t.rcon('pokeodds setRate 4096').split('\n').filter((l) => l.trim() && !l.startsWith('>')).join(' | '));
  const after = JSON.parse(fs.readFileSync(COBBLEMON_CFG, 'utf8')).shinyRate;
  t.check('gravou shinyRate=4096 na config do Cobblemon', after === 4096, 'arquivo=' + after);
  t.check('/pokeodds mostra a nova taxa', t.rcon('pokeodds').includes('1/4096'));
  t.rcon(`pokeodds setRate ${before}`);
  t.check('voltou ao valor original', JSON.parse(fs.readFileSync(COBBLEMON_CFG, 'utf8')).shinyRate === before);

  t.rcon(`clear ${name}`, `clearparty ${name}`, `clearpc ${name}`);
  console.log('== fim');
  bot.quit();
  await t.sleep(500);
  process.exit(process.exitCode || 0);
})().catch((e) => { console.log('ERRO NO TESTE: ' + (e && e.stack || e)); process.exit(2); });
